// The app's shadcn select renders an accessible combobox and a portalled
// listbox. Interact with what a user sees rather than the native form proxy.
async function choose(page, combobox, value) {
  await combobox.click()
  await page.getByRole('option').and(page.locator(`[data-value=${JSON.stringify(value)}]`)).click()
}
async function selected(combobox) { return combobox.getAttribute('data-value') }
async function waitForSelected(page, selector, value) {
  await page.waitForFunction(({ selector, value }) => document.querySelector(selector)?.getAttribute('data-value') === value, { selector, value })
}

